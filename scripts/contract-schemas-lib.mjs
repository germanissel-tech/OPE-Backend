// JSON Schemas of the configuration files (feature 019, D-04; ADR-032): the two levels of the
// release (`config/platform.json`, `config/treatment-defaults.json`) and what a merchant may
// declare (referenced by the hand-written seed schema) are derived from the bundled contract,
// never written by hand. OpenAPI 3.0 → JSON Schema 2020-12 is mechanical on the subset the
// contract uses (ADR-014): every `$ref` is collected into `$defs` and rewritten; no `$id`, so
// that a hand-written schema may reference these by relative path (editors and Ajv agree); anything
// outside the subset (`nullable`, `discriminator`) fails the generation. Deterministic: the
// order of the bundle, two-space JSON, LF.
import { readFileSync } from "node:fs";
import path from "node:path";
import { parse } from "yaml";
import { bundlePath, repoRoot } from "./lib.mjs";

export const generatedSchemasDir = path.join(repoRoot, "generated", "schemas");

/** The contract schemas that become configuration schemas, with the file each one becomes. */
export const CONFIG_SCHEMAS = /** @type {const} */ ([
  ["PlatformConfiguration", "platform-configuration.schema.json"],
  ["TreatmentDefaults", "treatment-defaults.schema.json"],
  ["MerchantConfigurationDeclared", "merchant-configuration-declared.schema.json"],
]);

const COMPONENT_REF = "#/components/schemas/";
const UNSUPPORTED = ["nullable", "discriminator"];

/**
 * Reads `components.schemas` of the bundle.
 * @param {string} [file]
 * @returns {Record<string, unknown>}
 */
export function readComponentSchemas(file = bundlePath) {
  const bundle = /** @type {unknown} */ (parse(readFileSync(file, "utf8")));
  const components = isObject(bundle) ? bundle["components"] : undefined;
  const schemas = isObject(components) ? components["schemas"] : undefined;
  if (!isObject(schemas)) throw new Error(`${file}: no components.schemas (bundle the contract first)`);
  return schemas;
}

/** @param {unknown} value @returns {value is Record<string, unknown>} */
function isObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/**
 * Rewrites `#/components/schemas/X` to `#/$defs/X`, collecting every definition reached.
 * @param {unknown} node
 * @param {Record<string, unknown>} schemas
 * @param {Map<string, unknown>} defs
 * @param {string} where
 * @returns {unknown}
 */
function convert(node, schemas, defs, where) {
  if (Array.isArray(node)) return node.map((item, i) => convert(item, schemas, defs, `${where}[${i}]`));
  if (!isObject(node)) return node;
  /** @type {Record<string, unknown>} */
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith("x-")) continue;
    if (UNSUPPORTED.includes(key))
      throw new Error(`${where}: \`${key}\` is outside the supported subset (ADR-014)`);
    if (key === "$ref" && typeof value === "string" && value.startsWith(COMPONENT_REF)) {
      const name = value.slice(COMPONENT_REF.length);
      if (!defs.has(name)) {
        defs.set(name, null); // placeholder: cycles end here
        defs.set(name, convert(schemas[name], schemas, defs, name));
      }
      out["$ref"] = `#/$defs/${name}`;
    } else {
      out[key] = convert(value, schemas, defs, `${where}.${key}`);
    }
  }
  return out;
}

/**
 * One configuration schema from a contract schema.
 * @param {string} name the contract schema
 * @param {Record<string, unknown>} schemas `components.schemas`
 * @returns {Record<string, unknown>} a JSON Schema 2020-12 document
 */
export function configSchemaOf(name, schemas) {
  if (!isObject(schemas[name])) throw new Error(`components.schemas.${name}: not a schema`);
  const defs = new Map();
  const root = /** @type {Record<string, unknown>} */ (convert(schemas[name], schemas, defs, name));
  const properties = isObject(root["properties"]) ? root["properties"] : {};
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $comment:
      "GENERATED by scripts/contract-schemas-lib.mjs from contracts/dist/openapi.yaml — DO NOT EDIT BY HAND. Regenerate with: npm run contract:types",
    title: name,
    ...root,
    // The file may point at this schema; `additionalProperties: false` must admit the key.
    properties: {
      $schema: { type: "string", description: "Path of this schema, for the editor." },
      ...properties,
    },
    ...(defs.size > 0 ? { $defs: Object.fromEntries(defs) } : {}),
  };
}

/**
 * Every configuration schema, rendered.
 * @param {string} [bundle]
 * @returns {[string, string][]} `[file, content]` pairs, absolute paths
 */
export function generateConfigSchemas(bundle = bundlePath) {
  const schemas = readComponentSchemas(bundle);
  return CONFIG_SCHEMAS.map(([name, file]) => [
    path.join(generatedSchemasDir, file),
    `${JSON.stringify(configSchemaOf(name, schemas), null, 2)}\n`,
  ]);
}
