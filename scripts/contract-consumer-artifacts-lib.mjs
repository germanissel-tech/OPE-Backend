// What a consumer copies of the contract (feature 040, ADR-044): `generated/contract/`, in the shape
// OPE-Web publishes in its `contract-artifact.md` and `constraints-artifact.md`. Eight files: the
// bundle, the two type files (copies of what the other emitters return, never re-read from disk),
// the capabilities module of the admin consumer (operation → capabilities and idempotency, and the
// vocabulary), the constraints module (what a form can verify of each request body: layer 1), and
// the identity of the contract (version and sha256, no commit: the same contract gives the same
// bytes wherever it is built). Deterministic: the order of the bundle, sorted names, LF endings.
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { parse } from "yaml";
import { bundlePath, repoRoot } from "./lib.mjs";

export const generatedContractDir = path.join(repoRoot, "generated", "contract");

const SCRIPT = "scripts/contract-consumer-artifacts-lib.mjs";
const BANNER = `GENERATED by ${SCRIPT} from contracts/dist/openapi.yaml — DO NOT EDIT BY HAND.`;
const REGENERATE = "Regenerate with: npm run contract:types";
const JS_BANNER = `// ${BANNER}\n// ${REGENERATE}\n`;

/** The consumer these modules describe; the portal, when it exists, gets modules of its own. */
export const CONSUMER = "admin";
/** An operation that identifies the principal asks for no capability (ADR-044). */
const IDENTIFIES = "x-identifies-principal";
const IDEMPOTENCY = "x-idempotency";
const CAPABILITIES = "x-required-capabilities";
const METHODS = ["get", "put", "post", "delete", "patch", "options", "head", "trace"];
const SCHEMA_REF = "#/components/schemas/";
const JSON_MEDIA = "application/json";
/** What a form can verify of one field without asking anybody. */
const FIELD_KEYS = [
  "minLength",
  "maxLength",
  "pattern",
  "minimum",
  "maximum",
  "minItems",
  "maxItems",
  "enum",
  "format",
];
const OPERATION_ID = /^[A-Za-z_$][\w$]*$/u;
const CAPABILITY = /^[a-z][a-z0-9-]*:[a-z][a-z0-9-]*$/u;

/**
 * @typedef {{ version: string; sha256: string }} Identity
 * @typedef {{ id: string; capabilities: string[]; idempotent: boolean }} ConsumerOperation
 * @typedef {{ required: string[]; fields: Record<string, FieldConstraints> }} MessageConstraints
 * @typedef {{ [key: string]: unknown; type?: string; ref?: string; items?: FieldConstraints }} FieldConstraints
 * @typedef {{ where: string; op: Record<string, unknown> }} Located an operation and where the bundle has it
 */

/**
 * @param {unknown} value
 * @returns {value is Record<string, unknown>}
 */
function isObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/**
 * @param {unknown} ref
 * @returns {string | undefined} the schema a `$ref` names
 */
function refName(ref) {
  return typeof ref === "string" && ref.startsWith(SCHEMA_REF) ? ref.slice(SCHEMA_REF.length) : undefined;
}

/**
 * The bundle as the consumer receives it: with its header, and its identity taken from the bytes the
 * consumer will hash — the copy, not the file in `contracts/dist/`.
 * @param {string} [file]
 * @returns {{ yaml: string; identity: Identity; doc: Record<string, unknown> }}
 */
export function readConsumerBundle(file = bundlePath) {
  if (!existsSync(file)) throw new Error(`${file} does not exist. Run npm run contract:bundle first.`);
  const text = readFileSync(file, "utf8").replace(/\r\n/gu, "\n");
  const yaml = `# ${BANNER}\n# ${REGENERATE}\n${text}`;
  const doc = /** @type {unknown} */ (parse(text));
  if (!isObject(doc)) throw new Error(`${file}: not a document`);
  const version = isObject(doc["info"]) ? doc["info"]["version"] : undefined;
  if (typeof version !== "string" || version === "") throw new Error(`${file}: no info.version`);
  const sha256 = createHash("sha256").update(yaml).digest("hex");
  return { yaml, identity: { version, sha256 }, doc };
}

/**
 * The operations of the consumer, in the order of the bundle.
 * @param {Record<string, unknown>} doc
 * @returns {Located[]}
 */
function locatedOperations(doc) {
  /** @type {Located[]} */
  const found = [];
  for (const [route, item] of Object.entries(isObject(doc["paths"]) ? doc["paths"] : {})) {
    if (!isObject(item)) continue;
    for (const method of METHODS) {
      const op = item[method];
      if (isObject(op) && Array.isArray(op["tags"]) && op["tags"].includes(CONSUMER)) {
        found.push({ where: `${method.toUpperCase()} ${route}`, op });
      }
    }
  }
  return found;
}

/**
 * One operation as the module states it. An operation without a capability is only admitted when
 * it identifies the principal: any other would draw its button for anybody.
 * @param {Located} located
 * @returns {ConsumerOperation}
 */
function consumerOperation({ where, op }) {
  const id = op["operationId"];
  if (typeof id !== "string" || !OPERATION_ID.test(id)) throw new Error(`${where}: no usable operationId`);
  const capabilities = op[CAPABILITIES];
  if (!Array.isArray(capabilities)) throw new Error(`${id}: no ${CAPABILITIES}`);
  if (capabilities.length === 0 && op[IDENTIFIES] !== true) {
    throw new Error(`${id}: no capability and not marked ${IDENTIFIES}`);
  }
  for (const capability of capabilities) {
    if (typeof capability !== "string" || !CAPABILITY.test(capability)) {
      throw new Error(`${id}: '${String(capability)}' is not shaped like a capability`);
    }
  }
  return { id, capabilities: capabilities.map(String), idempotent: IDEMPOTENCY in op };
}

/**
 * Every operation of the consumer, in the order of the bundle, each with a usable id and no id twice.
 * @param {Record<string, unknown>} doc
 * @returns {ConsumerOperation[]}
 */
export function consumerOperations(doc) {
  const operations = locatedOperations(doc).map(consumerOperation);
  if (operations.length === 0) throw new Error(`the bundle has no operation tagged ${CONSUMER}`);
  const ids = operations.map((o) => o.id);
  const repeated = ids.filter((id, at) => ids.indexOf(id) !== at);
  if (repeated.length > 0) throw new Error(`operationId repeated: ${repeated.join(", ")}`);
  return operations;
}

/** @param {readonly string[]} list */
const quoted = (list) => list.map((each) => `'${each}'`).join(", ");

/**
 * The capabilities module, as values and as declarations: literals travel as literals so that a
 * typo in the consumer does not compile.
 * @param {Identity} identity
 * @param {ConsumerOperation[]} operations
 * @returns {{ js: string; dts: string }}
 */
export function renderCapabilities(identity, operations) {
  const vocabulary = [...new Set(operations.flatMap((o) => o.capabilities))].sort();
  const js = `${JS_BANNER}
/** The contract this module was derived from. */
export const CONTRACT = { version: '${identity.version}', sha256: '${identity.sha256}' }

/** The consumer this module describes: its operations and its vocabulary. */
export const CONSUMER = '${CONSUMER}'

/** Every capability some ${CONSUMER} operation requires, sorted. */
export const CAPABILITIES = [${quoted(vocabulary)}]

/** What the contract demands of each ${CONSUMER} operation. */
export const OPERATIONS = {
${operations.map((o) => `  ${o.id}: { capabilities: [${quoted(o.capabilities)}], idempotent: ${o.idempotent} },`).join("\n")}
}
`;
  const dts = `${JS_BANNER}
/** The contract this module was derived from. */
export declare const CONTRACT: {
  readonly version: '${identity.version}'
  readonly sha256: '${identity.sha256}'
}

/** The consumer this module describes: its operations and its vocabulary. */
export declare const CONSUMER: '${CONSUMER}'

/** Every capability some ${CONSUMER} operation requires, sorted. */
export declare const CAPABILITIES: readonly [${quoted(vocabulary)}]
export type Capability = (typeof CAPABILITIES)[number]

/** What the contract demands of each ${CONSUMER} operation. */
export declare const OPERATIONS: {
${operations
  .map(
    (o) =>
      `  readonly ${o.id}: {\n    readonly capabilities: readonly [${quoted(o.capabilities)}]\n    readonly idempotent: ${o.idempotent}\n  }`,
  )
  .join("\n")}
}
export type OperationId = keyof typeof OPERATIONS
`;
  return { js, dts };
}

/**
 * What a form can verify of one property: its type and bounds, a nested object by name, an array
 * by its items. A `$ref` to an object is the name of that object, which gets constraints of its
 * own; a `$ref` to anything else (a string with an enum, a bounded number) is the field it stands
 * for, read through — a form verifies a value, not a name. A default or a description is not
 * emitted: the omission is the server's and the label is the application's.
 * @param {unknown} schema
 * @param {Record<string, unknown>} schemas the components, to read a `$ref` through
 * @returns {FieldConstraints}
 */
function fieldOf(schema, schemas) {
  if (!isObject(schema)) return {};
  const nested = refName(schema["$ref"]);
  if (nested !== undefined) {
    const target = schemas[nested];
    if (!isObject(target))
      throw new Error(`a property references ${SCHEMA_REF}${nested}, which the bundle does not have`);
    return target["type"] === "object" ? { type: "object", ref: nested } : fieldOf(target, schemas);
  }
  /** @type {FieldConstraints} */
  const field = {};
  if (typeof schema["type"] === "string") field.type = schema["type"];
  for (const key of FIELD_KEYS) if (schema[key] !== undefined) field[key] = schema[key];
  if (schema["items"] !== undefined) field.items = fieldOf(schema["items"], schemas);
  return field;
}

/**
 * The schemas a property names, directly or as the items of an array.
 * @param {Record<string, unknown>} properties
 * @returns {string[]}
 */
function referenced(properties) {
  /** @type {string[]} */
  const names = [];
  for (const each of Object.values(properties)) {
    if (!isObject(each)) continue;
    const items = isObject(each["items"]) ? each["items"]["$ref"] : undefined;
    const inner = refName(each["$ref"]) ?? refName(items);
    if (inner !== undefined) names.push(inner);
  }
  return names;
}

/**
 * The schema a request body names, if it names one.
 * @param {Record<string, unknown>} op
 * @returns {string | undefined}
 */
function bodySchemaOf(op) {
  const content = isObject(op["requestBody"]) ? op["requestBody"]["content"] : undefined;
  const json = isObject(content) ? content[JSON_MEDIA] : undefined;
  const schema = isObject(json) ? json["schema"] : undefined;
  return isObject(schema) ? refName(schema["$ref"]) : undefined;
}

/**
 * The constraints of every object schema some request body of the consumer names, directly or
 * through another (a nested object is typed just the same); response schemas never, nobody types
 * them. Sorted by name.
 * @param {Record<string, unknown>} doc
 * @returns {Map<string, MessageConstraints>}
 */
export function consumerConstraints(doc) {
  const components = isObject(doc["components"]) ? doc["components"] : {};
  const schemas = isObject(components["schemas"]) ? components["schemas"] : {};
  /** @type {Map<string, MessageConstraints>} */
  const wanted = new Map();
  /** @type {[string, string][]} name and where it was named */
  const pending = locatedOperations(doc).flatMap(({ where, op }) => {
    const name = bodySchemaOf(op);
    return name === undefined ? [] : [/** @type {[string, string]} */ ([name, where])];
  });
  for (let next = pending.shift(); next !== undefined; next = pending.shift()) {
    const [name, where] = next;
    if (wanted.has(name)) continue;
    const schema = schemas[name];
    if (!isObject(schema))
      throw new Error(`${where} references ${SCHEMA_REF}${name}, which the bundle does not have`);
    if (schema["type"] !== "object") continue;
    const properties = isObject(schema["properties"]) ? schema["properties"] : {};
    wanted.set(name, {
      required: Array.isArray(schema["required"]) ? schema["required"].map(String) : [],
      fields: Object.fromEntries(
        Object.entries(properties).map(([property, each]) => [property, fieldOf(each, schemas)]),
      ),
    });
    pending.push(
      ...referenced(properties).map((inner) => /** @type {[string, string]} */ ([inner, `schema ${name}`])),
    );
  }
  if (wanted.size === 0) throw new Error(`no request body of the ${CONSUMER} consumer references a schema`);
  return new Map([...wanted.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/**
 * The constraints module: one key per schema, typed so that a misspelt name does not compile.
 * @param {Identity} identity
 * @param {Map<string, MessageConstraints>} constraints
 * @returns {{ js: string; dts: string }}
 */
export function renderConstraints(identity, constraints) {
  const names = [...constraints.keys()];
  const literal = JSON.stringify(Object.fromEntries(constraints), null, 2);
  const js = `${JS_BANNER}
/** The contract this module was derived from. */
export const CONTRACT = { version: '${identity.version}', sha256: '${identity.sha256}' }

/** What a form can verify locally of each request body of the ${CONSUMER} consumer (layer 1). */
export const CONSTRAINTS = ${literal}
`;
  const dts = `${JS_BANNER}
/** The contract this module was derived from. */
export declare const CONTRACT: {
  readonly version: '${identity.version}'
  readonly sha256: '${identity.sha256}'
}

/** What the contract demands of one field; the same shape \`@ope/core\` validates with. */
export type FieldConstraints = {
  readonly type?: string
  readonly ref?: string
  readonly minLength?: number
  readonly maxLength?: number
  readonly pattern?: string
  readonly minimum?: number
  readonly maximum?: number
  readonly minItems?: number
  readonly maxItems?: number
  readonly items?: FieldConstraints
  readonly enum?: readonly (string | number | boolean)[]
  readonly format?: string
}

/** What the contract demands of one request body. */
export type MessageConstraints = {
  readonly required: readonly string[]
  readonly fields: Readonly<Record<string, FieldConstraints>>
}

/** What a form can verify locally of each request body of the ${CONSUMER} consumer (layer 1). */
export declare const CONSTRAINTS: {
${names.map((n) => `  readonly ${n}: MessageConstraints`).join("\n")}
}
export type ConstrainedSchema = keyof typeof CONSTRAINTS
`;
  return { js, dts };
}

/**
 * The identity of the contract, without a commit: what identifies the contract is its bytes.
 * @param {Identity} identity
 * @returns {string}
 */
export function renderIdentity(identity) {
  return `${JSON.stringify({ $comment: `${BANNER} ${REGENERATE}`, ...identity }, null, 2)}\n`;
}

/**
 * The eight files of `generated/contract/`, as [file, content], from the bundle and from what the
 * other emitters return for the two type files.
 * @param {string} apiDts the content of generated/api.d.ts
 * @param {string} problemTypesDts the content of generated/problem-types.d.ts
 * @param {string} [bundle]
 * @returns {[string, string][]}
 */
export function generateConsumerArtifacts(apiDts, problemTypesDts, bundle = bundlePath) {
  const { yaml, identity, doc } = readConsumerBundle(bundle);
  const capabilities = renderCapabilities(identity, consumerOperations(doc));
  const constraints = renderConstraints(identity, consumerConstraints(doc));
  const at = (/** @type {string} */ name) => path.join(generatedContractDir, name);
  return [
    [at("openapi.yaml"), yaml],
    [at("api.d.ts"), apiDts],
    [at("problem-types.d.ts"), problemTypesDts],
    [at("capabilities.js"), capabilities.js],
    [at("capabilities.d.ts"), capabilities.dts],
    [at("constraints.js"), constraints.js],
    [at("constraints.d.ts"), constraints.dts],
    [at("identity.json"), renderIdentity(identity)],
  ];
}
