// The catalogue of problem types (contracts/problem-types.yaml, the source of every RFC 9457
// `type`) as the server needs it at runtime: a JavaScript module with the namespace and the
// table of status and title by slug, and its declaration with the literals so that the status
// of a response is still checked against the contract at compile time. Deterministic: the
// order of the catalogue, LF line endings.
import { readFileSync } from "node:fs";
import path from "node:path";
import { parse } from "yaml";
import { repoRoot } from "./lib.mjs";

export const problemTypesSource = path.join(repoRoot, "contracts", "problem-types.yaml");
export const generatedProblemTypesJs =
  process.env["OPE_PROBLEM_TYPES_FILE"] ?? path.join(repoRoot, "generated", "problem-types.js");
export const generatedProblemTypesDts = generatedProblemTypesJs.replace(/\.js$/, ".d.ts");

const HEADER =
  "// GENERATED by scripts/contract-problem-types.mjs from contracts/problem-types.yaml — DO NOT EDIT BY HAND.\n" +
  "// Regenerate with: npm run contract:types\n\n";

/** @typedef {{ slug: string; status: number; title: string }} ProblemType */

/**
 * The catalogue as the YAML declares it, in its order.
 * @param {string} [file]
 * @returns {{ namespace: string; types: ProblemType[] }}
 */
export function readProblemTypes(file = problemTypesSource) {
  const parsed = /** @type {unknown} */ (parse(readFileSync(file, "utf8")));
  if (typeof parsed !== "object" || parsed === null) throw new Error(`${file}: not a catalogue`);
  const namespace = Reflect.get(parsed, "namespace");
  const raw = Reflect.get(parsed, "types");
  if (typeof namespace !== "string" || !Array.isArray(raw)) {
    throw new Error(`${file}: expected \`namespace\` and \`types\``);
  }
  const types = raw.map((entry, i) => {
    const slug = Reflect.get(entry, "slug");
    const status = Reflect.get(entry, "status");
    const title = Reflect.get(entry, "title");
    if (typeof slug !== "string" || typeof status !== "number" || typeof title !== "string") {
      throw new Error(`${file}: types[${i}] needs slug, status and title`);
    }
    return { slug, status, title };
  });
  return { namespace, types };
}

/** A slug as an object key: quoted only when it is not an identifier. */
const key = (/** @type {string} */ slug) => (/^[A-Za-z_$][\w$]*$/.test(slug) ? slug : JSON.stringify(slug));

/**
 * The runtime module and its declaration.
 * @param {{ namespace: string; types: ProblemType[] }} catalogue
 * @returns {{ js: string; dts: string }}
 */
export function renderProblemTypes({ namespace, types }) {
  const entries = types.map(
    (t) => `  ${key(t.slug)}: Object.freeze({ status: ${t.status}, title: ${JSON.stringify(t.title)} }),`,
  );
  const js =
    HEADER +
    `export const PROBLEM_NAMESPACE = ${JSON.stringify(namespace)};\n\n` +
    "/** Status and title of every problem type of the contract, by slug (RFC 9457). */\n" +
    "export const PROBLEM_TYPES = Object.freeze({\n" +
    entries.join("\n") +
    "\n});\n";
  const declared = types.map(
    (t) =>
      `  readonly ${key(t.slug)}: { readonly status: ${t.status}; readonly title: ${JSON.stringify(t.title)} };`,
  );
  const dts =
    HEADER +
    `export declare const PROBLEM_NAMESPACE: ${JSON.stringify(namespace)};\n\n` +
    "/** Status and title of every problem type of the contract, by slug (RFC 9457). */\n" +
    "export declare const PROBLEM_TYPES: {\n" +
    declared.join("\n") +
    "\n};\n\n" +
    "/** A slug of the catalogue: the `code` of every catalogued domain error. */\n" +
    "export type ProblemSlug = keyof typeof PROBLEM_TYPES;\n";
  return { js, dts };
}

/**
 * Both artefacts from the catalogue file.
 * @param {string} [file]
 * @returns {{ js: string; dts: string }}
 */
export function generateProblemTypes(file = problemTypesSource) {
  return renderProblemTypes(readProblemTypes(file));
}
