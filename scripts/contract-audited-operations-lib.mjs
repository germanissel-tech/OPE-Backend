// Which operations the contract orders to be audited, as a type the compiler can read (feature
// 021). The rule is not written anywhere by hand: an operation is audited when its consumer is the
// administration and it asks for at least one capability that is not a read. The tag of the
// operation fixes the consumer (ADR-020) and the map says which tag belongs to whom, so both
// sources are the contract itself. Deterministic: the order of the bundle, LF line endings.
import { readFileSync } from "node:fs";
import path from "node:path";
import { parse } from "yaml";
import { bundlePath, repoRoot } from "./lib.mjs";

export const apiMapSource = path.join(repoRoot, "contracts", "api-map.yaml");
export const generatedAuditedOperationsDts =
  process.env["OPE_AUDITED_OPERATIONS_FILE"] ?? path.join(repoRoot, "generated", "audited-operations.d.ts");

const HEADER =
  "// GENERATED by scripts/contract-audited-operations-lib.mjs from the contract bundle and\n" +
  "// contracts/api-map.yaml — DO NOT EDIT BY HAND.\n" +
  "// Regenerate with: npm run contract:types\n\n";

/** The consumer whose operations leave a record of what an operator did (ADR-031). */
const ADMIN = "admin";
/** A capability that only reads never changes anything, so there is nothing to audit. */
const READ = ":read";
const METHODS = ["get", "put", "post", "delete", "patch", "options", "head", "trace"];

/**
 * Which tag belongs to which consumer, as the map declares it.
 * @param {string} [file]
 * @returns {Map<string, string>} tag → consumer
 */
export function consumerByTag(file = apiMapSource) {
  const parsed = /** @type {unknown} */ (parse(readFileSync(file, "utf8")));
  const consumers = Reflect.get(parsed ?? {}, "consumers");
  if (typeof consumers !== "object" || consumers === null) throw new Error(`${file}: no consumers`);
  /** @type {Map<string, string>} */
  const byTag = new Map();
  for (const [consumer, raw] of Object.entries(consumers)) {
    const tags = Reflect.get(raw ?? {}, "tags");
    if (!Array.isArray(tags)) continue;
    for (const tag of tags) if (typeof tag === "string") byTag.set(tag, consumer);
  }
  return byTag;
}

/**
 * The operationIds the contract orders to be audited, in the order of the bundle.
 * @param {string} [bundle]
 * @param {string} [map]
 * @returns {string[]}
 */
export function readAuditedOperations(bundle = bundlePath, map = apiMapSource) {
  const byTag = consumerByTag(map);
  const parsed = /** @type {unknown} */ (parse(readFileSync(bundle, "utf8")));
  const paths = Reflect.get(parsed ?? {}, "paths");
  if (typeof paths !== "object" || paths === null) throw new Error(`${bundle}: no paths`);
  /** @type {string[]} */
  const audited = [];
  for (const item of Object.values(paths)) {
    for (const method of METHODS) {
      const operation = Reflect.get(item ?? {}, method);
      if (typeof operation !== "object" || operation === null) continue;
      const id = Reflect.get(operation, "operationId");
      if (typeof id !== "string") continue;
      if (isAudited(operation, byTag)) audited.push(id);
    }
  }
  return audited;
}

/**
 * The rule, in one place: the administration, and something that is not only read.
 * @param {object} operation
 * @param {Map<string, string>} byTag
 * @returns {boolean}
 */
function isAudited(operation, byTag) {
  const tags = Reflect.get(operation, "tags");
  const owner = Array.isArray(tags) ? byTag.get(String(tags[0])) : undefined;
  if (owner !== ADMIN) return false;
  const capabilities = Reflect.get(operation, "x-required-capabilities");
  if (!Array.isArray(capabilities)) return false;
  return capabilities.some((c) => typeof c === "string" && !c.endsWith(READ));
}

/**
 * The declaration: the union of the audited operationIds, or `never` when there is none.
 * @param {string[]} audited
 * @returns {string}
 */
export function renderAuditedOperations(audited) {
  // The empty case is one line (` never`); the rest is one member per line, each with its bar.
  const union = audited.length === 0 ? " never" : audited.map((id) => `\n  | ${JSON.stringify(id)}`).join("");
  return (
    HEADER +
    "/**\n" +
    " * The operations that leave an entry in the administration log: the consumer is the\n" +
    " * administration and the operation asks for something that is not only a read. Nobody\n" +
    " * chooses this; changing it means changing the contract.\n" +
    " */\n" +
    `export type AuditedOperation =${union};\n`
  );
}

/**
 * The declaration from the contract.
 * @param {string} [bundle]
 * @param {string} [map]
 * @returns {string}
 */
export function generateAuditedOperations(bundle = bundlePath, map = apiMapSource) {
  return renderAuditedOperations(readAuditedOperations(bundle, map));
}
